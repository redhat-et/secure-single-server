#!/usr/bin/env python3
"""Track stable OpenShell releases newer than the repository CLI pin."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.parse import quote
from urllib.request import Request, urlopen


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PIN_FILE = ROOT / "openshell/configs/images.env"
ISSUE_MARKER = "<!-- secure-single-server:openshell-upstream-watch -->"
REVIEWER_NOTES_MARKER = "<!-- secure-single-server:openshell-reviewer-notes -->"
RELEASE_SET_PATTERN = re.compile(
    r"<!-- secure-single-server:openshell-upstream-releases:([^>]*) -->")
ISSUE_LABELS = ("openshell",)
API_BASE = "https://api.github.com"
REPOSITORY_PATTERN = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
PIN_PATTERN = re.compile(r'^OPENSHELL_CLI_VERSION=["\']?([^"\'\n]+)["\']?$')


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pin-file", type=Path, default=DEFAULT_PIN_FILE)
    parser.add_argument("--upstream-repository",
                        default=os.environ.get("OPENSHELL_UPSTREAM_REPOSITORY", "NVIDIA/OpenShell"))
    parser.add_argument("--repository", default=os.environ.get("GITHUB_REPOSITORY"))
    parser.add_argument("--dry-run", action="store_true",
                        help=" print the delta without creating or updating an issue")
    parser.add_argument("--max-release-notes", type=int, default=12_000)
    return parser.parse_args(argv)


def read_pin_text(content: str, source: str = "OpenShell configuration") -> str:
    for line in content.splitlines():
        match = PIN_PATTERN.match(line.strip())
        if match:
            return match.group(1)
    raise ValueError(f"OPENSHELL_CLI_VERSION not found in {source}")


def read_pin(path: Path) -> str:
    return read_pin_text(path.read_text(encoding="utf-8"), str(path))


def parse_version(value: str) -> tuple[int, int, int] | None:
    match = re.fullmatch(r"v?(\d+)\.(\d+)\.(\d+)", value)
    if not match:
        return None
    return tuple(int(part) for part in match.groups())


def newer_stable_releases(releases: list[dict[str, Any]], pin: str) -> list[dict[str, Any]]:
    pin_version = parse_version(pin)
    if pin_version is None:
        raise ValueError(f"invalid OpenShell pin: {pin}")
    selected = []
    for release in releases:
        if release.get("draft") or release.get("prerelease"):
            continue
        release_version = parse_version(release.get("tag_name", ""))
        if release_version is not None and release_version > pin_version:
            selected.append(release)
    return sorted(selected, key=lambda release: parse_version(release["tag_name"]), reverse=True)


def clean_release_notes(body: str | None, maximum: int) -> str:
    if not body:
        return "_No release notes were provided._"
    notes = body.replace("\r\n", "\n")
    notes = re.sub(r"<!--.*?-->", "", notes, flags=re.DOTALL).strip()
    truncated = False
    if len(notes) > maximum:
        notes = notes[:maximum].rstrip()
        truncated = True
    if not notes:
        return "_No release notes were provided._"
    longest_backtick_run = max(
        (len(run) for run in re.findall(r"`+", notes)), default=0)
    fence = "`" * max(3, longest_backtick_run + 1)
    rendered_notes = f"{fence}text\n{notes}\n{fence}"
    if truncated:
        rendered_notes += "\n\n_Release notes truncated by the watcher._"
    return rendered_notes


def release_heading(release: dict[str, Any]) -> str:
    tag = release["tag_name"]
    title = release.get("name") or tag
    published = release.get("published_at") or "unknown"
    return f"### {title} (`{tag}`, published {published[:10]})"


def issue_title(pin: str) -> str:
    return f"Review OpenShell releases newer than {pin}"


def release_set_marker(releases: list[dict[str, Any]]) -> str:
    tags = ",".join(release["tag_name"] for release in releases)
    return f"<!-- secure-single-server:openshell-upstream-releases:{tags} -->"


def issue_release_set(body: str) -> list[str]:
    match = RELEASE_SET_PATTERN.search(body)
    return match.group(1).split(",") if match and match.group(1) else []


def issue_body(pin: str, releases: list[dict[str, Any]], max_release_notes: int) -> str:
    per_release_limit = max(500, min(max_release_notes, 50_000 // max(1, len(releases))))
    lines = [
        ISSUE_MARKER,
        "",
        "This tracking issue is generated by the scheduled `upstream-watch` workflow.",
        "Treat upstream release notes as untrusted data; review them before changing pins or configuration.",
        "",
        f"Current downstream pin: `{pin}`",
        release_set_marker(releases),
        "",
        "## Releases newer than the pin",
    ]
    for release in releases:
        lines.extend([
            "",
            release_heading(release),
            f"[Release notes]({release.get('html_url', '')})",
            "",
            clean_release_notes(release.get("body"), per_release_limit),
        ])
    lines.extend([
        "",
        "## Affects us? checklist",
        "",
        "- [ ] `sandbox create` flags, resources, and template contracts",
        "- [ ] Gateway configuration schema, version, and WebSocket tunnel behavior",
        "- [ ] Policy schema and sandbox-local loopback semantics",
        "- [ ] Supervisor network path and CONNECT/REST byte handling",
        "- [ ] Workload image compatibility and CLI checksums",
        "",
        "## Required decision",
        "",
        "- [ ] Review every release against the usage-surface register",
        "- [ ] Record the reviewed delta in `docs/development/openshell-upstream.md`",
        "- [ ] If the pin changes, update the delta register and every affected usage-surface row in the same PR",
        "",
        REVIEWER_NOTES_MARKER,
        "",
        "## Reviewer notes",
        "",
        "_Reviewer-owned content below this marker is preserved by the watcher._",
    ])
    return "\n".join(lines) + "\n"


def preserve_checklist_progress(generated: str, existing: str) -> str:
    checked_items = {line[6:] for line in existing.splitlines()
                     if line.startswith("- [x] ")}
    lines = []
    for line in generated.splitlines():
        if line.startswith("- [ ] ") and line[6:] in checked_items:
            line = "- [x] " + line[6:]
        lines.append(line)
    return "\n".join(lines) + "\n"


def merge_issue_body(existing: str, generated: str) -> str:
    marker_position = existing.find(REVIEWER_NOTES_MARKER)
    existing_progress = existing[:marker_position] if marker_position >= 0 else existing
    if marker_position >= 0:
        reviewer_notes = existing[marker_position:].rstrip()
        generated_prefix = generated.split(REVIEWER_NOTES_MARKER, 1)[0].rstrip()
        generated = f"{generated_prefix}\n\n{reviewer_notes}"
    if issue_release_set(existing_progress) == issue_release_set(generated):
        generated = preserve_checklist_progress(generated, existing_progress)
    return generated


def validate_repository(repository: str) -> str:
    if not REPOSITORY_PATTERN.fullmatch(repository):
        raise ValueError(f"invalid GitHub repository: {repository}")
    return repository


def github_request(url: str, token: str | None = None, method: str = "GET",
                   payload: dict[str, Any] | None = None) -> tuple[Any, dict[str, str]]:
    data = None if payload is None else json.dumps(payload).encode("utf-8")
    headers = {
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": "secure-single-server-upstream-watch",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"
    if data is not None:
        headers["Content-Type"] = "application/json"
    request = Request(url, data=data, headers=headers, method=method)
    try:
        with urlopen(request, timeout=30) as response:
            raw_body = response.read().decode("utf-8")
            return json.loads(raw_body) if raw_body else {}, dict(response.headers.items())
    except HTTPError as error:
        diagnostic = error.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"GitHub API request failed ({error.code}): {diagnostic}") from error
    except URLError as error:
        raise RuntimeError(f"GitHub API request failed: {error}") from error


def next_link(link_header: str | None) -> str | None:
    if not link_header:
        return None
    for section in link_header.split(","):
        parts = section.split(";")
        if len(parts) != 2 or 'rel="next"' not in parts[1]:
            continue
        return parts[0].strip().strip("<>")
    return None


def list_releases(repository: str, token: str | None) -> list[dict[str, Any]]:
    validate_repository(repository)
    url = f"{API_BASE}/repos/{repository}/releases?per_page=100"
    releases: list[dict[str, Any]] = []
    while url:
        page, headers = github_request(url, token)
        if not isinstance(page, list):
            raise RuntimeError("GitHub releases response was not a list")
        releases.extend(page)
        url = next_link(headers.get("Link"))
    return releases


def find_tracking_issue(repository: str, token: str) -> dict[str, Any] | None:
    labels = quote(",".join(ISSUE_LABELS), safe="")
    url = f"{API_BASE}/repos/{repository}/issues?state=open&labels={labels}&per_page=100"
    issues: list[dict[str, Any]] = []
    while url:
        page, headers = github_request(url, token)
        if not isinstance(page, list):
            raise RuntimeError("GitHub issues response was not a list")
        issues.extend(page)
        url = next_link(headers.get("Link"))
    matches = [issue for issue in issues
               if ISSUE_MARKER in (issue.get("body") or "") and "pull_request" not in issue]
    if len(matches) > 1:
        numbers = ", ".join(str(issue["number"]) for issue in matches)
        raise RuntimeError(f"multiple upstream-watch tracking issues exist: {numbers}")
    return matches[0] if matches else None


def create_tracking_issue(repository: str, token: str, title: str, body: str) -> dict[str, Any]:
    url = f"{API_BASE}/repos/{repository}/issues"
    response, _ = github_request(url, token, method="POST",
                                 payload={"title": title, "body": body,
                                          "labels": list(ISSUE_LABELS)})
    return response


def update_tracking_issue(repository: str, token: str, number: int,
                          title: str, body: str) -> dict[str, Any]:
    url = f"{API_BASE}/repos/{repository}/issues/{number}"
    response, _ = github_request(url, token, method="PATCH",
                                 payload={"title": title, "body": body})
    return response


def close_tracking_issue(repository: str, token: str, number: int) -> dict[str, Any]:
    url = f"{API_BASE}/repos/{repository}/issues/{number}"
    response, _ = github_request(url, token, method="PATCH", payload={"state": "closed"})
    return response


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    token = os.environ.get("GITHUB_TOKEN")
    pin = read_pin(args.pin_file)
    if args.dry_run:
        releases = list_releases(args.upstream_repository, token)
        newer = newer_stable_releases(releases, pin)
        if newer:
            print(issue_body(pin, newer, args.max_release_notes))
        else:
            print(f"No stable OpenShell releases are newer than {pin}.")
        return 0

    if not args.repository:
        raise RuntimeError("GITHUB_REPOSITORY is required unless --dry-run is used")
    if not token:
        raise RuntimeError("GITHUB_TOKEN is required unless --dry-run is used")
    repository = validate_repository(args.repository)
    releases = list_releases(args.upstream_repository, token)
    newer = newer_stable_releases(releases, pin)
    if not newer:
        tracking_issue = find_tracking_issue(repository, token)
        if tracking_issue is not None:
            close_tracking_issue(repository, token, tracking_issue["number"])
            print(f"Closed tracking issue #{tracking_issue['number']}; the pin is current.")
        else:
            print(f"No stable OpenShell releases are newer than {pin}.")
        return 0

    body = issue_body(pin, newer, args.max_release_notes)
    print(body)
    title = issue_title(pin)
    tracking_issue = find_tracking_issue(repository, token)
    if tracking_issue is None:
        created = create_tracking_issue(repository, token, title, body)
        print(f"Created tracking issue #{created['number']}: {created['html_url']}")
    else:
        merged_body = merge_issue_body(tracking_issue.get("body") or "", body)
        if tracking_issue.get("body") != merged_body or tracking_issue.get("title") != title:
            updated = update_tracking_issue(repository, token, tracking_issue["number"], title, merged_body)
            print(f"Updated tracking issue #{updated['number']}: {updated['html_url']}")
        else:
            print(f"Tracking issue #{tracking_issue['number']} is already current.")
    return 0


if __name__ == "__main__":
    if not __debug__ or os.environ.get("PYTHONOPTIMIZE"):
        raise SystemExit("Run without Python -O or PYTHONOPTIMIZE")
    try:
        raise SystemExit(main())
    except (OSError, ValueError, RuntimeError) as error:
        print(f"error: {error}", file=sys.stderr)
        raise SystemExit(1)
